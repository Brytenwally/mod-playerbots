#!/usr/bin/env python3
"""Writes src/Ai/Coa/CoaLegendaryClassData.h from docs/area52/classes/<class>-build.tsv and -enchants.tsv."""
import csv
import pathlib

ROOT = pathlib.Path(__file__).resolve().parents[2]
CLASSES = pathlib.Path(ROOT, "docs/area52/classes")
HEADER = pathlib.Path(ROOT, "src/Ai/Coa/CoaLegendaryClassData.h")

# file stem, spec word ("talents spec <word>"); the rest of each class is in src/Ai/Coa/CoaLegendaryClasses.cpp
META = [
    ("mystic-knight", "mknight"),
    ("hoplite", "hoplite"),
    ("naturalist", "naturalist"),
]


def rows(path):
    with open(path, newline="", encoding="utf-8") as handle:
        return list(csv.DictReader(handle, delimiter="\t"))


def main():
    out = [
        "/*",
        " * GENERATED by apps/area52/generate_legendary_class_data.py from the class tables in docs/area52/classes.",
        " * Do not edit by hand - the next run overwrites it.",
        " */",
        "",
        "#ifndef PLAYERBOTS_COALEGENDARYCLASSDATA_H",
        "#define PLAYERBOTS_COALEGENDARYCLASSDATA_H",
        "",
        "#include <array>",
        "#include <cstdint>",
        "",
        "struct CoaLegendaryPick",
        "{",
        "    uint32_t spell;",
        "    uint32_t level;",
        "};",
        "",
    ]
    for stem, spec in META:
        picks = rows(CLASSES / f"{stem}-build.tsv")
        enchants = rows(CLASSES / f"{stem}-enchants.tsv")
        if len(enchants) != 17:
            raise SystemExit(f"{stem}: {len(enchants)} enchant slots, not 17")
        name = spec.capitalize()
        out.append(f"inline constexpr std::array<CoaLegendaryPick, {len(picks)}> CoaLegendaryPicks{name} = {{{{")
        out += [f"    {{ {row['spell']}, {row['level']} }}," for row in picks]
        out.append("}};")
        out.append("")
        out.append(f"inline constexpr std::array<uint32_t, 17> CoaLegendaryEnchants{name} = {{")
        slots = [row["spell"] for row in enchants]
        for start in range(0, 17, 6):
            out.append("    " + ", ".join(slots[start:start + 6]) + ",")
        out.append("};")
        out.append("")
    out.append("#endif")
    HEADER.write_text("\n".join(out) + "\n", encoding="utf-8")


if __name__ == "__main__":
    main()
